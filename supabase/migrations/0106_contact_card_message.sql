-- 0106. 연락처 전달을 채팅 말풍선으로 (docs/32 §3-3)
--
-- 지금은 예약 카드 안쪽에 붙어 있어서, 대화가 몇 줄만 쌓여도 위로 밀려 안 보인다.
-- 연락처는 '작가가 보낸 것' 이므로 대화의 한 사건으로 타임라인에 남는 게 맞다.
--
-- 알림·안읽음은 만들지 않는다 — 보내는 순간 별도 알림이 이미 나가고,
-- 말풍선은 그 사건의 기록이자 [연락처 받기] 버튼이 붙는 자리다.

alter type public.message_type add value if not exists 'contact_card';
