create table public.spots (
  id          uuid primary key default gen_random_uuid(),
  /*
    URL 조각. **영문만** 쓴다 — 한글 slug 는 인코딩/디코딩 사고가 날 자리를 만든다
    (Next 16 은 동적 param 을 자동 디코딩하지 않는다).
  */
  slug        text not null unique,
  name        text not null,
  /*
    광역 지자체. 목록을 지역별로 묶는 데 쓴다.
    전국으로 넓히는 중인데 "서울 스냅 촬영 장소" 질의도 계속 잡아야 해서
    한 지면 안에서 지역 섹션으로 나눈다. 지역이 더 늘면 /spots/<city> 로 쪼갠다.
  */
  city        text not null,
  area        text not null,                  -- 자치구
  address     text not null default '',
  station     text,                           -- 최인접 역·출구. 출처에 없으면 null — 지어내지 않는다
  descr       text not null default '',       -- `desc` 는 SQL 예약어라 피한다
  tip         text not null default '',
  /*
    `photos.location_text` 매칭 키워드.
    photos.region 은 전 건이 비어 있어(2026-08-31 확인) 쓸 수 없다.
    작가가 자유 텍스트로 적는 location_text 만 실제 데이터가 있다.
  */
  keywords    text[] not null default '{}',
  /*
    무엇으로 검증했는지. **끄고 켤 때의 판단 근거**라 필수로 둔다.
    검증 안 된 정보를 웹에 올리면 SEO 가 아니라 리스크다 — 장소 정보는 틀리면
    사람을 헛걸음시킨다.
  */
  source      text not null default '',
  published   boolean not null default false,
  sort_order  integer not null default 0,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);

create index idx_spots_live on public.spots (published, city, sort_order);

alter table public.spots enable row level security;

create policy spots_select on public.spots for select using (
  published or public.is_admin()
);
create policy spots_write on public.spots for all
  using (public.is_admin())
  with check (public.is_admin());

create trigger trg_spots_updated
  before update on public.spots
  for each row execute function public.set_updated_at();

grant select on public.spots to anon, authenticated;
grant insert, update, delete on public.spots to authenticated;

