-- ─────────────────────────────────────────────
-- 0129. 초상 사용 거부 — **약관이 약속한 권리를 행사할 자리가 없었다.**
--
-- 세 문서가 같은 말을 한다:
--
--   · 작가 이용약관 13조 4항  — "회원이 원하지 않는다는 의사를 밝힌 경우에는 사용하지 않으며
--                                 서비스에도 게재할 수 없습니다"
--   · 작가 입점 계약 4조 3항  — "그 의사를 밝힌 사진은 게재할 수 없습니다"
--   · 광고 소재 사용 동의 「대상」 — "회원이 포트폴리오 사용을 원하지 않는다고 밝힌 결과물은 제외"
--
-- 그런데 **의사를 밝힐 방법이 서비스 어디에도 없었다**(2026-09-17 점검). 회원 입장에서는
-- 약속된 권리를 행사할 수 없고, 작가 입장에서는 누가 거부했는지 알 방법이 없다. 분쟁이
-- 나면 우리가 댈 근거가 "약관에 적어 뒀다" 뿐이다.
--
-- ⚠️ 예약 단위다. 사진 단위가 아니다 — 회원은 자기 촬영 결과물이 어떤 사진으로 올라갈지
--    모르고, 애초에 작가가 올리기 전에 미리 밝혀 둬야 실효가 있다. 작가는 그 예약 건의
--    사진을 올릴 때 경고를 본다.
--
-- ⚠️ 시각을 남긴다(boolean 아님). "언제 밝혔는가" 가 곧 그 시점 이후의 게재가 위반인지를
--    가르는 기준이다. 껐다 켰다를 반복하면 마지막 의사만 남는데, 그건 의도한 동작이다 —
--    회원은 언제든 마음을 바꿀 수 있고 유효한 건 현재 의사다.
-- ─────────────────────────────────────────────

alter table public.bookings
  add column if not exists portrait_optout_at timestamptz;

comment on column public.bookings.portrait_optout_at is
  '회원이 이 촬영 결과물의 포트폴리오·홍보 사용을 거부한 시각. null 이면 거부하지 않음 '
  '(작가약관 13조 4항 · 입점계약 4조 3항).';

-- 작가가 자기 예약 중 거부된 건을 찾는 조회 — 거부는 소수라 부분 인덱스로 충분하다
create index if not exists bookings_portrait_optout_idx
  on public.bookings (photographer_id) where portrait_optout_at is not null;
