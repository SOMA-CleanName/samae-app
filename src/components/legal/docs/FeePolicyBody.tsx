import { Article, B, Ol, P, Table } from "@/components/legal/LegalDoc";
import { DEFAULT_FEE_RATE, FEE_VAT_RATE } from "@/lib/platform-fee";
import { POLICY_EFFECTIVE_DATE } from "@/lib/policy-version";
// 지급 기한은 계산하는 쪽(settlementSla)에서 읽는다 — 위약금 표가 PENALTY_BANDS 를 읽는 것과 같은 이유로,
// 지면에 손으로 적으면 기한을 바꿀 때 한쪽만 바뀐다
import { SETTLEMENT_SLA_BUSINESS_DAYS } from "@/lib/settlement-sla";


/*
  FeePolicyBody — 약관 **본문만**. 화면 껍데기(제목·시행일·뒤로가기)는 쓰는 쪽이 붙인다.

  두 곳에서 같은 글을 보여주기 위해 뺐다:
    · 공개 지면  `/terms/fees`            — 누구나 읽는다
    · 동의 플로우 `/studio/agree/…`          — 작가가 끝까지 읽고 동의한다

  ⚠️ 조문을 여기서 고치지 말 것. 정본은 노션이고, 문안을 바꾸면 `policy-version.ts` 의
     버전도 같이 올려야 한다 — 버전이 그대로면 이미 동의한 작가에게 다시 안 묻는다.

  ⚠️ **요율은 작가마다 다를 수 있다.** 어드민에서 개별 요율을 정할 수 있는데(fee_rate),
     이 지면이 전역 기본값만 보여 주면 "20% 라고 적혀 있는데 내 정산은 다르다" 가 된다
     (2026-09-17 신고). 그래서 `rate` 를 받는다.

       · 공개 지면(/terms/fees) — 누가 읽는지 모르므로 기본값. 개별 요율은 입점
         동의서에 따른다는 안내를 함께 낸다
       · 입점 동의 화면 — 그 작가에게 **실제로 적용되는** 요율을 넘긴다
*/
export function FeePolicyBody({
  /**
   * 이 작가에게 적용되는 요율(0.2 = 20%).
   * null·미지정이면 전역 기본값으로 쓰고, "작가별로 다를 수 있다" 안내를 함께 낸다
   * (정액 작가도 여기로 온다 — 퍼센트로 표현할 수 없는 값이다).
   */
  rate,
}: {
  rate?: number | null;
} = {}) {
  const effective = rate ?? DEFAULT_FEE_RATE;
  // 지면과 계산이 어긋나지 않게 한 곳에서 만든다
  const RATE_PCT = +(effective * 100).toFixed(2);
  const GROSS_PCT = +(effective * 100 * (1 + FEE_VAT_RATE)).toFixed(2);
  const isDefault = rate == null || rate === DEFAULT_FEE_RATE;

  return (
    <>
    <Article n="제1조" title="중개 수수료">
      <Ol>
        <li>
          중개 수수료는 촬영 대금의 <B>{RATE_PCT}%</B>입니다. 부가가치세는 별도입니다.
          {isDefault && (
            <>
              {" "}
              이는 기본 요율이며, 작가별로 다르게 정한 경우에는 입점 동의서에 기재된 요율을
              적용합니다.
            </>
          )}
        </li>
        <li>
          사업자 유형에 따라 실질 부담이 다를 수 있습니다.
          <Table
            head={["사업자 유형", "세금계산서", "매입세액공제", "실질 부담"]}
            rows={[
              ["일반과세자", "회사가 발급", "가능", `${RATE_PCT}%`],
              ["간이과세자", "회사가 발급", "불가", `${GROSS_PCT}%`],
              ["사업자 미등록", "영수증 발급", "해당 없음", `${GROSS_PCT}%`],
            ]}
          />
        </li>
        <li>
          중개 수수료는 촬영 대금 전체를 기준으로 산정합니다. 촬영비, 출장비, 추가 보정·인원·시간 등에 따른
          추가금을 포함하며, 회원이 스튜디오 등 제3자에게 직접 지급하는 금액은 촬영 대금에 포함하지 않습니다.
        </li>
        <li>회원이 서비스 화면에 표시된 금액 외에 추가로 부담하는 수수료는 없습니다.</li>
      </Ol>
    </Article>

    <Article n="제2조" title="수수료율의 변경">
      <Ol>
        <li>회사는 중개 수수료율을 변경할 수 있습니다.</li>
        <li>
          작가에게 불리한 변경은 적용일 30일 전에 공지하고 작가에게 개별 통지합니다. 그 밖의 변경은 적용일
          7일 전에 공지합니다.
        </li>
        <li>작가가 변경에 동의하지 않는 경우 적용일 전에 사매 작가 입점 계약을 해지할 수 있습니다.</li>
        <li>변경 전에 확정된 예약에는 예약 확정 시점의 요율을 적용합니다.</li>
      </Ol>
    </Article>

    <Article n="제3조" title="정산의 시기">
      <Ol>
        <li>
          정산 대상은 작가가 결과물을 회원에게 전달하고 서비스 내에서 전달 사실을 알린 건입니다. 회사는 전달
          사실이 확인되면 해당 건을 정산 대상에 포함시키며, 별도의 승인 절차를 두지 않습니다.
        </li>
        <li>
          회사는 제1항의 전달 사실이 확인된 날부터 <B>{SETTLEMENT_SLA_BUSINESS_DAYS}영업일 이내</B>에 정산금을
          지급합니다. 각 건의 지급 기한은 스튜디오 &gt; 정산에서 확인할 수 있습니다.
        </li>
        <li>
          회사는 정산 지급 전에 산정 내역(촬영 건별 대금, 중개 수수료, 공제 항목, 세무 처리 내역)을 정산
          내역서로 작가에게 제공합니다.
        </li>
      </Ol>
    </Article>

    <Article n="제4조" title="1회 정산 한도">
      <Ol>
        <li>
          회사는 결제대행사와의 계약상 한도 등 불가피한 사유가 있는 경우 1회 정산에서 지급하는 총액을 제한할
          수 있습니다.
        </li>
        <li>
          이 경우 회사는 정산일 전에 해당 작가에게 사유와 지급 예정일을 통지하고, 지급되지 않은 금액은 다음
          정산일에 다른 정산금보다 우선하여 지급합니다.
        </li>
      </Ol>
    </Article>

    <Article n="제5조" title="정산 계좌">
      <Ol>
        <li>정산 계좌는 작가 본인 명의여야 합니다. 사업자 등록 작가의 경우 사업자 명의를 포함합니다.</li>
        <li>계좌 정보의 오류나 미갱신으로 인한 정산상 불이익은 작가에게 귀속됩니다.</li>
      </Ol>
    </Article>

    <Article n="제6조" title="세무 처리와 증빙">
      <Ol>
        <li>
          촬영 대금에 관한 세금계산서·현금영수증 등 회원에 대한 증빙은 작가가 발급합니다. 다만 회사가 법령에
          따라 발급 의무를 지는 경우에는 회사가 발급합니다.
        </li>
        <li>
          중개 수수료에 관한 증빙은 회사가 작가에게 발급합니다. 사업자 등록 작가에게는 세금계산서를, 사업자
          미등록 작가에게는 지출증빙용 현금영수증을 발급합니다. 작가는 이를 필요경비 증빙으로 사용할 수 있습니다.
        </li>
        <li>
          회사는 작가에게 지급하는 정산금에 대하여 <B>원천징수를 하지 않습니다.</B> 회사는 회원과 작가
          사이의 거래를 중개할 뿐 촬영 대금의 지급 주체가 아니므로 소득세법상 원천징수의무자에 해당하지
          않습니다. 촬영 대금은 작가 본인의 사업소득이며, 신고·납부는 작가가 직접 합니다.
        </li>
        <li>
          회사는 작가의 신고를 돕기 위해 연간 정산 내역(거래 건별 대금·수수료·실수령)을 제공합니다.
          스튜디오 &gt; 정산에서 연도별로 내려받을 수 있습니다.
        </li>
        <li>
          작가가 사업자 유형이나 사업자등록번호를 사실과 다르게 등록하거나 변경 사항을 갱신하지 않아 발생한
          세무상 불이익은 작가에게 귀속됩니다.
        </li>
      </Ol>
    </Article>

    <Article n="제7조" title="정산금의 공제">
      <Ol>
        <li>
          회사는 다음 각 호의 금액을 작가의 정산금에서 공제할 수 있습니다.
          <Ol>
            <li>제8조에 따른 작가 귀책 취소 시 중개 수수료 상당액</li>
            <li>제9조에 따른 정산 후 환불 금액</li>
            <li>사매 작가 입점 계약의 서비스 외부 거래 금지 조항 위반에 따라 회사가 작가에게 청구하는 금액</li>
            <li>그 밖에 사매 작가 이용약관, 사매 작가 입점 계약 또는 이 정책에 따라 작가가 회사에 지급할 의무가 있는 금액</li>
          </Ol>
        </li>
        <li>
          회사는 공제 전에 그 사유와 금액을 작가에게 통지하며, 작가는 통지일부터 7일 이내에 이의를 제기할 수
          있습니다. 회사는 이의 내용을 검토하여 회신하고, 이의가 이유 있는 경우 공제하지 않거나 공제액을
          조정합니다.
        </li>
        <li>
          <B>회원의 사정이나 회사의 사정으로 예약이 취소되거나 환불이 이루어진 경우에는 작가에게 제1항의 금액을 청구하지 않습니다.</B>
        </li>
        <li>정산금이 없거나 부족한 경우 회사는 작가에게 직접 청구합니다.</li>
      </Ol>
    </Article>

    <Article n="제8조" title="작가 귀책 취소 시 중개 수수료">
      <Ol>
        <li>
          사매 취소·환불 정책 제8조에 따라 작가의 사정으로 촬영이 취소된 경우, 회사는 해당 촬영 대금을 기준으로
          산정한 중개 수수료 상당액을 작가에게 청구합니다.
        </li>
        <li>제1항의 금액은 제7조에 따라 정산금에서 공제합니다.</li>
        <li>사매 취소·환불 정책 제9조의 불가항력에 해당하는 경우에는 청구하지 않습니다.</li>
      </Ol>
    </Article>

    <Article n="제9조" title="정산 후 환불">
      <P>
        정산이 완료된 뒤에 작가의 귀책으로 환불이 발생하는 경우, 이미 작가에게 정산된 금액은 제7조에 따라
        다음 정산금에서 공제하며, 정산금이 없거나 부족한 경우 작가에게 직접 청구합니다.
      </P>
    </Article>

    <Article n="제10조" title="위약금의 배분">
      <Ol>
        <li>
          회원이 지급한 위약금은 서비스를 통해 발생한 작가의 수익으로 보아{" "}
          <B>작가 {100 - RATE_PCT}%, 회사 {RATE_PCT}%</B>의 비율로 배분합니다.
        </li>
        <li>제1항의 비율은 제1조의 중개 수수료율과 연동되며, 수수료율이 변경되면 같은 비율로 변경됩니다.</li>
        <li>
          위약금의 부가가치세 및 소득 구분은 촬영 대금과 다를 수 있으며, 그 처리 내역은 정산 내역서에
          별도로 표시합니다.
        </li>
      </Ol>
    </Article>

    <Article n="제11조" title="정책의 변경">
      <Ol>
        <li>
          회사는 관련 법령을 위반하지 않는 범위에서 이 정책을 변경할 수 있으며, 변경 시 적용일과 변경 사유를
          명시하여 적용일 7일 전부터 공지합니다. 작가에게 불리한 변경은 30일 전부터 공지하고 개별 통지합니다.
        </li>
        <li>수수료율의 변경은 제2조에 따릅니다.</li>
        <li>작가가 불리한 변경에 동의하지 않는 경우 적용일 전에 사매 작가 입점 계약을 해지할 수 있습니다.</li>
      </Ol>
    </Article>

    <section>
      <h2 className="mb-2 text-base font-semibold text-fg">부칙</h2>
      <P>이 정책은 {POLICY_EFFECTIVE_DATE || "시행일(게시 공지 후 확정)"}부터 적용합니다.</P>
    </section>
    </>
  );
}
