export type Spot = {
  /** URL 조각. 한글 대신 영문 — 디코딩 사고가 날 자리를 안 만든다. */
  slug: string;
  name: string;
  /**
   * 광역 지자체. 목록을 지역별로 묶는 데 쓴다.
   *
   * 전국으로 넓히는 중인데 "서울 스냅 촬영 장소" 질의도 계속 잡아야 해서,
   * 한 지면 안에서 지역 섹션으로 나눈다. 나중에 지역이 더 늘면 /spots/<city> 로 쪼갠다.
   */
  city: string;
  /** 자치구 */
  area: string;
  address: string;
  /** 가장 가까운 역·출구. 원본에 없으면 null — 지어내지 않는다. */
  station: string | null;
  desc: string;
  tip: string;
  /**
   * photos.location_text 매칭 키워드.
   *
   * photos.region 은 전 건이 비어 있어(2026-08-31 확인) 쓸 수 없다.
   * 작가가 자유 텍스트로 적는 location_text 만 실제 데이터가 있다.
   */
  keywords: string[];
  published: boolean;
  /** 무엇으로 검증했는지. 끄고 켤 때 판단 근거가 된다. */
  source: string;
};

